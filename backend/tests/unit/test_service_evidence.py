# ── confirm_upload ────────────────────────────────────────────────────────────


class TestConfirmUpload:
    def _seed_pending_evidence(
        self,
        er: FakeEvidenceRepository,
        cr: FakeClaimRepository,
        evidence_id: str = EVIDENCE_ID,
        claim_id: str = CLAIM_ID,
    ) -> dict[str, Any]:
        """Seed both claim and evidence records for confirm tests."""
        claim_item = _make_claim_item(claim_id=claim_id)
        cr.seed(claim_item)
        ev_item = _make_evidence_item(evidence_id=evidence_id, claim_id=claim_id)
        er.seed(ev_item)
        return ev_item

    def test_successful_confirmation(self) -> None:
        """Happy path — evidence transitions to UPLOAD_COMPLETE."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        result = svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        assert result["status"] == "UPLOAD_COMPLETE"
        assert "uploadedAt" in result

    def test_evidence_transition_persisted(self) -> None:
        """After confirmation, the persisted evidence record is UPLOAD_COMPLETE."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        saved = er.get(EVIDENCE_ID)
        assert saved is not None
        assert saved["status"] == "UPLOAD_COMPLETE"
        assert "uploadedAt" in saved

    def test_s3_object_missing_raises_validation_error(self) -> None:
        """If S3 object does not exist, ValidationError is raised."""
        svc, cr, er, _ = _make_evidence_service(object_exists=False)
        self._seed_pending_evidence(er, cr)

        with pytest.raises(ValidationError) as exc_info:
            svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)
        assert exc_info.value.error_code == "VALIDATION_ERROR"

    def test_evidence_already_complete_is_idempotent(self) -> None:
        """Confirming already-complete evidence returns the existing state."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        cr.seed(_make_claim_item())
        ev = _make_evidence_item(evidence_id=EVIDENCE_ID, status="UPLOAD_COMPLETE")
        ev["uploadedAt"] = FIXED_TIME
        er.seed(ev)

        result = svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        assert result["status"] == "UPLOAD_COMPLETE"
        # Conditional update not called (already complete) — evidence unchanged
        saved = er.get(EVIDENCE_ID)
        assert saved is not None
        assert saved["status"] == "UPLOAD_COMPLETE"

    def test_repeated_confirmation_is_safe(self) -> None:
        """Calling confirm_upload twice does not corrupt the record."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        r1 = svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)
        r2 = svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        assert r1["status"] == "UPLOAD_COMPLETE"
        assert r2["status"] == "UPLOAD_COMPLETE"

    def test_claim_ownership_failure_raises_forbidden(self) -> None:
        """Claim belonging to another claimant raises ForbiddenError."""
        svc, cr, er, _ = _make_evidence_service()
        cr.seed(_make_claim_item(claimant_id=OTHER_CLAIMANT_ID))
        er.seed(_make_evidence_item())

        with pytest.raises(ForbiddenError):
            svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

    def test_evidence_ownership_failure_raises_forbidden(self) -> None:
        """Evidence belonging to another claimant raises ForbiddenError."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        cr.seed(_make_claim_item())
        ev = _make_evidence_item(evidence_id=EVIDENCE_ID, claim_id=CLAIM_ID)
        ev["claimantId"] = OTHER_CLAIMANT_ID
        er.seed(ev)

        with pytest.raises(ForbiddenError):
            svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

    def test_evidence_not_found_raises_not_found_error(self) -> None:
        """Non-existent evidenceId raises NotFoundError (EVIDENCE_NOT_FOUND)."""
        svc, cr, er, _ = _make_evidence_service()
        cr.seed(_make_claim_item())

        with pytest.raises(NotFoundError) as exc_info:
            svc.confirm_upload(CLAIM_ID, "EVD-missing", CLAIMANT_ID)
        assert exc_info.value.error_code == "EVIDENCE_NOT_FOUND"

    def test_evidence_belonging_to_different_claim_raises_not_found(self) -> None:
        """Evidence with a different claimId raises NotFoundError."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        cr.seed(_make_claim_item())
        ev = _make_evidence_item(evidence_id=EVIDENCE_ID, claim_id="CLM-different")
        er.seed(ev)

        with pytest.raises(NotFoundError) as exc_info:
            svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)
        assert exc_info.value.error_code == "EVIDENCE_NOT_FOUND"

    def test_claim_transitions_to_evidence_submitted(self) -> None:
        """After confirmation, claim status transitions to EVIDENCE_SUBMITTED."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        claim = cr.get(CLAIM_ID)
        assert claim is not None
        assert claim["status"] == "EVIDENCE_SUBMITTED"

    def test_claim_stays_evidence_submitted_on_second_confirm(self) -> None:
        """Second confirmation does not corrupt claim status."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)
        svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        claim = cr.get(CLAIM_ID)
        assert claim is not None
        assert claim["status"] == "EVIDENCE_SUBMITTED"

    def test_concurrent_confirmation_conditional_update_returns_false(self) -> None:
        """When conditional evidence update returns False, service handles it gracefully."""
        svc, cr, er, s3 = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        # Pre-transition evidence to UPLOAD_COMPLETE to simulate a concurrent request
        er_item = er.get(EVIDENCE_ID)
        assert er_item is not None
        er_item["status"] = "UPLOAD_COMPLETE"
        er_item["uploadedAt"] = FIXED_TIME

        # Our request still proceeds without error — idempotent result
        result = svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)
        assert result["status"] == "UPLOAD_COMPLETE"

    def test_no_ai_processing_invoked(self) -> None:
        """confirm_upload must not call any AI/ML service."""
        svc, cr, er, s3 = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        # Replace s3_repo with a mock and verify only expected methods are called
        mock_s3 = MagicMock()
        mock_s3.object_exists.return_value = True
        mock_s3.generate_presigned_put_url.return_value = "https://s3.example.com/key"
        svc._s3_repo = mock_s3

        svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        # Only object_exists should be called — no AI/ML methods
        mock_s3.object_exists.assert_called_once()
        mock_s3.generate_presigned_put_url.assert_not_called()

    def test_claim_not_found_during_confirm_raises_not_found(self) -> None:
        """confirm_upload raises NotFoundError if claim doesn't exist."""
        svc, _, er, _ = _make_evidence_service()
        er.seed(_make_evidence_item())

        with pytest.raises(NotFoundError) as exc_info:
            svc.confirm_upload("CLM-missing", EVIDENCE_ID, CLAIMANT_ID)
        assert exc_info.value.error_code == "CLAIM_NOT_FOUND"

    def test_response_contains_required_evidence_fields(self) -> None:
        """Confirm response contains all required evidence fields."""
        svc, cr, er, _ = _make_evidence_service(object_exists=True)
        self._seed_pending_evidence(er, cr)

        result = svc.confirm_upload(CLAIM_ID, EVIDENCE_ID, CLAIMANT_ID)

        for key in (
            "evidenceId",
            "claimId",
            "evidenceType",
            "status",
            "storageKey",
            "createdAt",
            "uploadedAt",
        ):
            assert key in result, f"Missing key in confirm response: {key}"
