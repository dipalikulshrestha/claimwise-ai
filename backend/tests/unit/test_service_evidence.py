"""
Unit tests for app.services.evidence_service — Task 5.

Uses in-memory fake repositories (from test_service_claims) and a fake
S3Repository.  No AWS credentials or real AWS calls required.

Covers:
  request_upload_url:
  - valid VIDEO / AUDIO / POLICY_DOCUMENT
  - invalid MIME type raises ValidationError (UNSUPPORTED_CONTENT_TYPE)
  - file size over limit raises ValidationError (FILE_SIZE_EXCEEDED)
  - claim not found raises NotFoundError
  - unauthorized claimant raises ForbiddenError
  - evidence saved as UPLOAD_PENDING
  - storageKey generated by backend (no filename)
  - original filename not included in storageKey
  - presignedUrl returned and used correct storage key
  - multiple evidence records for same type are supported
  - response contains required fields

  confirm_upload:
  - successful confirmation → UPLOAD_COMPLETE
  - S3 object missing → ValidationError
  - evidence already UPLOAD_COMPLETE → idempotent (returns existing)
  - repeated confirmation is safe
  - claim ownership failure → ForbiddenError
  - evidence ownership failure → ForbiddenError
  - evidence belongs to different claim → NotFoundError/ForbiddenError
  - evidence transition is persisted
  - claim transitions to EVIDENCE_SUBMITTED
  - concurrent confirmation behavior (conditional update returns False)
  - no AI processing invoked
"""

