# ── Fake S3 repository ────────────────────────────────────────────────────────


class FakeS3Repository:
    """In-memory S3Repository replacement for unit tests."""

    def __init__(self, object_exists_default: bool = True) -> None:
        self._existing_keys: set[str] = set()
        self._object_exists_default = object_exists_default
        self.presigned_url_calls: list[dict[str, Any]] = []

    def generate_presigned_put_url(
        self,
        key: str,
        content_type: str,
        expiry_seconds: int,
    ) -> str:
        self.presigned_url_calls.append(
            {"key": key, "content_type": content_type, "expiry_seconds": expiry_seconds}
        )
        return f"https://s3.example.com/{key}?presigned=true"

    def object_exists(self, key: str) -> bool:
        if key in self._existing_keys:
            return True
        return self._object_exists_default

    def add_object(self, key: str) -> None:
        self._existing_keys.add(key)

    def remove_object(self, key: str) -> None:
        self._existing_keys.discard(key)


# ── Factory helpers ───────────────────────────────────────────────────────────


def _make_evidence_service(
    claim_repo: FakeClaimRepository | None = None,
    evidence_repo: FakeEvidenceRepository | None = None,
    s3_repo: FakeS3Repository | None = None,
    size_limits: dict[str, int] | None = None,
    object_exists: bool = True,
) -> tuple[EvidenceService, FakeClaimRepository, FakeEvidenceRepository, FakeS3Repository]:
    cr = claim_repo or FakeClaimRepository()
    er = evidence_repo or FakeEvidenceRepository()
    s3 = s3_repo or FakeS3Repository(object_exists_default=object_exists)
    svc = EvidenceService(
        claim_repo=cr,
        evidence_repo=er,
        s3_repo=s3,  # type: ignore[arg-type]
        size_limits=size_limits or DEFAULT_SIZE_LIMITS,
        presigned_url_expiry_seconds=900,
        clock=lambda: FIXED_TIME,
    )
    return svc, cr, er, s3


# ── request_upload_url ────────────────────────────────────────────────────────


class TestRequestUploadUrl:
    def test_valid_video_evidence(self) -> None:
        """Valid VIDEO request returns expected response fields."""
        svc, cr, er, s3 = _make_evidence_service()
        cr.seed(_make_claim_item())

        result = svc.request_upload_url(CLAIM_ID, CLAIMANT_ID, VALID_VIDEO_BODY)

        assert result["evidenceId"].startswith("EVD-")
        assert result["claimId"] == CLAIM_ID
        assert result["status"] == "UPLOAD_PENDING"
        assert result["evidenceType"] == "VIDEO"
        assert result["contentType"] == "video/mp4"
        assert "presignedUrl" in result
        assert "storageKey" in result
        assert "urlExpiresAt" in result

    def test_valid_audio_evidence(self) -> None:
        """Valid AUDIO request returns expected response fields."""
        svc, cr, _, _ = _make_evidence_service()
        cr.seed(_make_claim_item())

        result = svc.request_upload_url(CLAIM_ID, CLAIMANT_ID, VALID_AUDIO_BODY)

        assert result["evidenceType"] == "AUDIO"
        assert result["contentType"] == "audio/mpeg"
        assert result["status"] == "UPLOAD_PENDING"

    def test_valid_policy_document_evidence(self) -> None:
        """Valid POLICY_DOCUMENT request returns expected response fields."""
        svc, cr, _, _ = _make_evidence_service()
        cr.seed(_make_claim_item())

        result = svc.request_upload_url(CLAIM_ID, CLAIMANT_ID, VALID_PDF_BODY)

        assert result["evidenceType"] == "POLICY_DOCUMENT"
        assert result["contentType"] == "application/pdf"
        assert result["status"] == "UPLOAD_PENDING"

    def test_evidence_saved_as_upload_pending(self) -> None:
        """Evidence record is persisted with UPLOAD_PENDING status."""
        svc, cr, er, _ = _make_evidence_service()
        cr.seed(_make_claim_item())

        result = svc.request_upload_url(CLAIM_ID, CLAIMANT_ID, VALID_VIDEO_BODY)

        saved = er.get(result["evidenceId"])
        assert saved is not None
        assert saved["status"] == "UPLOAD_PENDING"

    def test_storage_key_generated_by_backend(self) -> None:
        """storageKey is generated by the service, not taken from the body."""
        svc, cr, er, _ = _make_evidence_service()
        cr.seed(_make_claim_item())

        body_with_key = {**VALID_VIDEO_BODY, "storageKey": "client/supplied/key"}
        result = svc.request_upload_url(CLAIM_ID, CLAIMANT_ID, body_with_key)

        assert result["storageKey"] != "client/supplied/key"
        assert result["storageKey"].startswith("claims/")
        assert result["storageKey"].endswith("/object")

    def test_original_filename_not_in_storage_key(self) -> None:
        """The original filename must not appear anywhere in the storage key."""
        svc, cr, _, _ = _make_evidence_service()
        cr.seed(_make_claim_item())

        body = {**VALID_VIDEO_BODY, "fileName": "accident-video.mp4"}
        result = svc.request_upload_url(CLAIM_ID, CLAIMANT_ID, body)

        assert "accident-video.mp4" not in result["storageKey"]
        assert "accident" not in result["storageKey"]

    def test_path_traversal_filename_does_not_affect_storage_key(self) -> None:
        """Path-traversal filename cannot influence the storage key."""
        svc, cr, _, _ = _make_evidence_service()
        cr.seed(_make_claim_item())

        body = {**VALID_PDF_BODY, "fileName": "../../etc/passwd"}
        result = svc.request_upload_url(CLAIM_ID, CLAIMANT_ID, body)

        assert result["storageKey"].startswith("claims/")
        assert result["storageKey"].endswith("/object")
        assert "etc" not in result["storageKey"]
        assert "passwd" not in result["storageKey"]

    def test_presigned_url_uses_generated_storage_key(self) -> None:
        """The presigned URL generation is called with the backend storage key."""
        svc, cr, _, s3 = _make_evidence_service()
        cr.seed(_make_claim_item())

